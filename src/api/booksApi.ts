export function fetchBooks(simulateError = false): Promise<ApiResponse<Book[]>> {
  return new Promise((resolve) => {
    setTimeout(() => {
      if (simulateError) {
        resolve({
          ok: false,
          error: 'Không thể kết nối đến máy chủ thư viện! Vui lòng thử lại sau.',
        });
      } else {
        resolve({
          ok: true,
          data: [...INITIAL_BOOKS],
        });
      }
    }, 500);
  });
}
